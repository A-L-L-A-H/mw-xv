package main

import (
	"encoding/base64"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

type TemplateEntry struct {
	ID               string   `json:"id"`
	CanonicalID      string   `json:"canonicalId"`
	Name             string   `json:"name"`
	Slogan           string   `json:"slogan"`
	Category         string   `json:"category"`
	Tags             []string `json:"tags"`
	Documentation    string   `json:"documentation"`
	Logo             string   `json:"logo"`
	Source           string   `json:"source"`
	DuplicateSources []string `json:"duplicateSources"`
	ServiceCount     int      `json:"serviceCount"`
	Services         []string `json:"services"`
	ComposeYaml      string   `json:"composeYaml"`
}

type Catalog struct {
	GeneratedAt string          `json:"generatedAt"`
	TotalCanonical int         `json:"totalCanonical"`
	Templates   []TemplateEntry `json:"templates"`
}

func main() {
	jsonPath := filepath.Join("packages", "orm-cloud", "scripts", "dist", "unified-template-catalog-ready.json")
	data, err := os.ReadFile(jsonPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Failed to read %s: %v\n", jsonPath, err)
		os.Exit(1)
	}

	var catalog Catalog
	if err := json.Unmarshal(data, &catalog); err != nil {
		fmt.Fprintf(os.Stderr, "Failed to parse JSON: %v\n", err)
		os.Exit(1)
	}

	// Filter to only ready templates (no restricted)
	// Already filtered in ready JSON

	// Group by category
	categoryMap := make(map[string][]TemplateEntry)
	for _, t := range catalog.Templates {
		categoryMap[t.Category] = append(categoryMap[t.Category], t)
	}

	// Build template string
	const tmpl = `// Code generated by generate_templates.go. DO NOT EDIT.

package main

import (
	"encoding/base64"
)

// PaasTemplateFromCatalog describes a one-click application template from the unified catalog.
type PaasTemplateFromCatalog struct {
	ID            string
	Name          string
	CanonicalID   string
	Slogan        string
	Category      string
	Tags          []string
	Documentation string
	Logo          string
	Source        string
	ComposeYamlB64 string
	ComposeYaml   string
	ServiceCount  int
	Services      []string
}

// UnifiedPaasTemplates returns the deduplicated, validator-compatible template catalog.
// Generated from packages/orm-cloud/scripts/dist/unified-template-catalog-ready.json
func UnifiedPaasTemplates() []PaasTemplateFromCatalog {
	return []PaasTemplateFromCatalog{
{{- range .Templates }}
		{
			ID:            {{ printf "%q" .ID }},
			Name:          {{ printf "%q" .Name }},
			CanonicalID:   {{ printf "%q" .CanonicalID }},
			Slogan:        {{ printf "%q" .Slogan }},
			Category:      {{ printf "%q" .Category }},
			Tags:          []string{{ joinQuoted .Tags }},
			Documentation: {{ printf "%q" .Documentation }},
			Logo:          {{ printf "%q" .Logo }},
			Source:        {{ printf "%q" .Source }},
			ComposeYamlB64: {{ printf "%q" .ComposeYamlB64 }},
			ServiceCount:  {{ .ServiceCount }},
			Services:      []string{{ joinQuoted .Services }},
		},
{{- end }}
	}
}

func init() {
	// Pre-decode base64 compose YAML for fast access at request time.
	for i := range unifiedPaasTemplatesCache {
		if unifiedPaasTemplatesCache[i].ComposeYamlB64 != "" {
			if decoded, err := base64.StdEncoding.DecodeString(unifiedPaasTemplatesCache[i].ComposeYamlB64); err == nil {
				unifiedPaasTemplatesCache[i].ComposeYaml = string(decoded)
			}
		}
	}
}

var unifiedPaasTemplatesCache = UnifiedPaasTemplates()

func GetUnifiedPaasTemplates() []PaasTemplateFromCatalog {
	return unifiedPaasTemplatesCache
}
`

	funcMap := template.FuncMap{
		"joinQuoted": func(slice []string) string {
			if len(slice) == 0 {
				return "{}"
			}
			quoted := make([]string, len(slice))
			for i, s := range slice {
				quoted[i] = fmt.Sprintf("%q", s)
			}
			return "{" + strings.Join(quoted, ", ") + "}"
		},
	}

	// Prepare data for template
	type tmplEntry struct {
		TemplateEntry
		ComposeYamlB64 string
	}

	var entries []tmplEntry
	for _, t := range catalog.Templates {
		b64 := base64.StdEncoding.EncodeToString([]byte(t.ComposeYaml))
		entries = append(entries, tmplEntry{
			TemplateEntry:  t,
			ComposeYamlB64: b64,
		})
	}

	t, err := template.New("gen").Funcs(funcMap).Parse(tmpl)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Template parse error: %v\n", err)
		os.Exit(1)
	}

	outPath := filepath.Join("apps", "control-plane", "paas_catalog_gen.go")
	f, err := os.Create(outPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Failed to create output: %v\n", err)
		os.Exit(1)
	}
	defer f.Close()

	if err := t.Execute(f, map[string]interface{}{"Templates": entries}); err != nil {
		fmt.Fprintf(os.Stderr, "Template execute error: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %s with %d templates across %d categories\n", outPath, len(entries), len(categoryMap))
}